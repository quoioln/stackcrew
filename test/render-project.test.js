import test from 'node:test';
import assert from 'node:assert/strict';
import { miniCtx } from '../test-helpers/render-ctx.js';
import { renderProject, assertUniquePaths } from '../src/render/index.js';
import { renderShared } from '../src/render/shared.js';
import { GENERATED_NOTICE } from '../src/render/notice.js';
import { StackcrewError } from '../src/errors.js';

const ALL = ['claude', 'cursor', 'codex', 'antigravity'];
const byPath = (ops, p) => ops.find((o) => o.path === p);

test('renders expected path set for all tools', async () => {
  const { ops } = renderProject(await miniCtx(ALL));
  const paths = ops.map((o) => o.path);
  for (const p of [
    '.claude/rules/stackcrew/core.md',
    '.cursor/rules/stackcrew/stack-demo-java.mdc',
    '.agents/rules/stackcrew-stack-demo-java.md',
    '.agents/skills/stackcrew-demo-java-rules/SKILL.md',
    '.codex/agents/stackcrew-demo-java-developer.toml',
    '.agents/agents/stackcrew-tech-lead.md',
    'docs/stackcrew/architecture-profile.md',
    '.stackcrew/guard.json',
    '.stackcrew/ci/Jenkinsfile.stackcrew.groovy',
    '.stackcrew/lint/demo.xml',
    'AGENTS.md',
    'CLAUDE.md',
  ]) {
    assert.ok(paths.includes(p), `missing ${p}`);
  }
  assert.equal(byPath(ops, 'AGENTS.md').kind, 'block');
});

test('warns cursor-duplicate-skills for claude+cursor+codex', async () => {
  const { warnings } = renderProject(await miniCtx(['claude', 'cursor', 'codex']));
  assert.ok(warnings.some((w) => w.startsWith('cursor-duplicate-skills')));
  assert.deepEqual(renderProject(await miniCtx(['claude'])).warnings, []);
});

test('guard.json merges language and stack rules and honors guard flag', async () => {
  const ctx = await miniCtx(['claude']);
  const g = JSON.parse(byPath(renderShared(ctx), '.stackcrew/guard.json').content);
  assert.equal(g.version, 1);
  assert.equal(g.enabled, true);
  assert.deepEqual(g.rules.map((r) => r.id), [...ctx.language.guard, ...ctx.stack.guard].map((r) => r.id));
  assert.ok(g.rules.length >= 1);
  ctx.profile.guard = false;
  const off = byPath(renderShared(ctx), '.stackcrew/guard.json');
  assert.equal(JSON.parse(off.content).enabled, false);
  assert.ok(off.content.endsWith('}\n'));
});

test('wire files rendered only when wired', async () => {
  const p = 'src/test/java/com/example/kyc/stackcrew/StackcrewArchitectureTest.java';
  const unwired = await miniCtx(['claude']);
  assert.equal(byPath(renderShared(unwired), p), undefined);
  assert.equal(renderShared(unwired).some((o) => o.path.startsWith('src/test/java')), false);

  const ctx = await miniCtx(['claude'], { wired: true });
  ctx.profile.java.basePackage = 'com.example.kyc';
  ctx.vars.basePackage = 'com.example.kyc';
  const op = byPath(renderShared(ctx), p);
  assert.ok(op, 'wire file missing');
  assert.ok(op.content.includes('package com.example.kyc.stackcrew;'));

  const empty = await miniCtx(['claude'], { wired: true });
  empty.vars.basePackage = '';
  empty.profile.java.basePackage = '';
  assert.equal(renderShared(empty).some((o) => o.path.startsWith('src/test/java')), false);
});

test('jenkins snippet pins the package version', async () => {
  const op = byPath(renderShared(await miniCtx(['claude'])), '.stackcrew/ci/Jenkinsfile.stackcrew.groovy');
  assert.ok(op.content.startsWith('// Generated by stackcrew 0.0.0-test: paste this stage'));
  assert.ok(op.content.includes('npx --yes stackcrew@0.0.0-test check --base "origin/${CHANGE_TARGET:-main}"'));
  assert.ok(!op.content.includes('{{sc:'));
});

test('architecture profile renders context, decisions and escapes pipes', async () => {
  const ctx = await miniCtx(['claude'], { addons: ['demo-addon'] });
  const empty = byPath(renderShared(ctx), 'docs/stackcrew/architecture-profile.md').content;
  assert.ok(empty.startsWith(GENERATED_NOTICE + '\n'));
  assert.ok(empty.includes('_No context recorded yet — run the stackcrew-init interview._'));
  assert.ok(empty.includes('_No decisions recorded yet._'));
  assert.ok(empty.includes('## How to change'));

  ctx.profile.context = { 'db|kind': 'pg|mysql', note: ['line1', 'line2', 'line3'].join(String.fromCharCode(13, 10)) };
  ctx.profile.decisions = [
    { id: 'D1', area: 'db', decision: 'Use PG', rationale: 'Mature', rejected: ['MySQL', 'Mongo'] },
    { id: 'D2', area: 'cache', decision: 'None', rationale: 'Small', rejected: [] },
  ];
  const md = byPath(renderShared(ctx), 'docs/stackcrew/architecture-profile.md').content;
  assert.ok(md.includes('| Key | Value |'));
  const BS = String.fromCharCode(92);
  assert.ok(md.includes('| db' + BS + '|kind | pg' + BS + '|mysql |'));
  assert.ok(!md.includes('| db|kind |'));
  assert.ok(md.includes('| note | line1 line2 line3 |'));
  assert.ok(md.includes('### D1 — db\n'));
  assert.ok(md.includes('**Decision:** Use PG'));
  assert.ok(md.includes('**Rejected:** MySQL; Mongo'));
  assert.ok(md.includes('**Rejected:** —'));
});

test('throws RENDER on duplicate path (case-folded) and docs/sdlc paths', () => {
  const op = (path) => ({ path, kind: 'owned', content: 'x' });
  assert.throws(() => assertUniquePaths([op('a.md'), op('A.md')]), (e) => e instanceof StackcrewError && e.code === 'RENDER' && /duplicate output path/.test(e.message));
  assert.throws(() => assertUniquePaths([op('docs/sdlc/x.md')]), (e) => e.code === 'RENDER');
  assert.throws(() => assertUniquePaths([op('Docs/SDLC/x.md')]), (e) => e.code === 'RENDER');
  assert.doesNotThrow(() => assertUniquePaths([op('a.md'), op('b.md')]));
});
