import test from 'node:test';
import assert from 'node:assert/strict';
import { miniCtx } from '../test-helpers/render-ctx.js';
import { parseFrontmatter } from '../src/util/frontmatter.js';
import { matchesAny } from '../src/util/glob.js';
import { GENERATED_NOTICE } from '../src/render/notice.js';
import { renderSkills } from '../src/render/skills.js';
import { renderClaude } from '../src/render/claude.js';

const OWNED = [
  '.claude/rules/stackcrew/**',
  '.claude/skills/stackcrew-*/**',
  '.claude/agents/stackcrew-*.md',
  '.cursor/rules/stackcrew/**',
  '.cursor/skills/stackcrew-*/**',
  '.cursor/agents/stackcrew-*.md',
  '.agents/rules/stackcrew-*.md',
  '.agents/skills/stackcrew-*/**',
  '.agent/skills/stackcrew-*/**',
  '.agents/agents/stackcrew-*.md',
  '.codex/agents/stackcrew-*.toml',
];
const byPath = (ops, p) => ops.find((o) => o.path === p);

test('core rule has no frontmatter and contains always-on text', async () => {
  const ctx = await miniCtx(['claude']);
  const op = byPath(renderClaude(ctx), '.claude/rules/stackcrew/core.md');
  assert.equal(op.kind, 'owned');
  assert.equal(op.content, GENERATED_NOTICE + '\n\n' + ctx.alwaysOn);
  assert.ok(!op.content.startsWith('---'));
});

test('stack rule frontmatter paths equal stack globs', async () => {
  const ctx = await miniCtx(['claude']);
  const op = byPath(renderClaude(ctx), `.claude/rules/stackcrew/${ctx.stack.rules.id}.md`);
  const { data, body } = parseFrontmatter(op.content);
  assert.deepEqual(data.paths, ['**/*.java']);
  assert.ok(body.startsWith('\n' + GENERATED_NOTICE + '\n\n') || body.startsWith(GENERATED_NOTICE + '\n\n'));
  assert.ok(op.content.includes('---\n' + GENERATED_NOTICE + '\n\n'));
});

test('claude and generic skills carry only name and description, never paths', async () => {
  // Claude Code hides a path-scoped skill until a matching file is touched: no slash command
  // at session start and no preload into role agents. So paths must never reach the output.
  const ctx = await miniCtx(['claude', 'codex']);
  for (const s of ctx.skills) s.paths = ['**/*.java'];
  const ops = renderSkills(ctx);
  const c = byPath(ops, '.claude/skills/stackcrew-demo-task/SKILL.md');
  const g = byPath(ops, '.agents/skills/stackcrew-demo-task/SKILL.md');
  assert.deepEqual(Object.keys(parseFrontmatter(c.content).data), ['name', 'description']);
  assert.equal(parseFrontmatter(g.content).data.paths, undefined);
  assert.deepEqual(Object.keys(parseFrontmatter(g.content).data), ['name', 'description']);
  assert.ok(c.content.includes('---\n' + GENERATED_NOTICE + '\n\n'));
  // supporting files copied verbatim, no notice
  const sup = byPath(ops, '.claude/skills/stackcrew-demo-advisor/patterns/x.md');
  assert.ok(sup);
  assert.ok(!sup.content.includes('Generated by stackcrew'));
  // command skills only in command dirs
  assert.ok(byPath(ops, '.agents/skills/stackcrew-init/SKILL.md'));
  assert.ok(!byPath(ops, '.claude/skills/stackcrew-init/SKILL.md'));
});

test('agent frontmatter lists preloaded skills', async () => {
  const ctx = await miniCtx(['claude']);
  const ops = renderClaude(ctx);
  for (const role of ctx.roles) {
    const op = byPath(ops, `.claude/agents/${role.name}.md`);
    const { data, body } = parseFrontmatter(op.content);
    assert.deepEqual(Object.keys(data).slice(0, 3), ['name', 'description', 'model']);
    assert.equal(data.name, role.name);
    assert.equal(data.model, role.model);
    if (role.skills.length > 0) assert.deepEqual(data.skills, role.skills);
    assert.ok(!op.content.includes('Generated by stackcrew'));
    assert.ok(body.includes(role.body.trim()));
  }
  assert.ok(ctx.roles.some((r) => r.skills.length > 0));
});

test('CLAUDE.md op is a block op', async () => {
  const ctx = await miniCtx(['claude']);
  const op = byPath(renderClaude(ctx), 'CLAUDE.md');
  assert.equal(op.kind, 'block');
  assert.equal(
    op.content,
    'stackcrew: coding rules for this repo are in .claude/rules/stackcrew/ (auto-loaded). Architecture decisions: docs/stackcrew/architecture-profile.md.',
  );
});

test('renderClaude is empty without claude tool', async () => {
  assert.deepEqual(renderClaude(await miniCtx(['codex'])), []);
});

test('no op path outside owned prefixes', async () => {
  const ctx = await miniCtx(['claude', 'cursor', 'codex', 'antigravity']);
  const ops = [...renderSkills(ctx), ...renderClaude(ctx)];
  assert.ok(ops.length > 0);
  for (const op of ops) {
    const ok = op.kind === 'block' ? op.path === 'CLAUDE.md' || op.path === 'AGENTS.md' : matchesAny(op.path, OWNED);
    assert.ok(ok, `unowned path ${op.path}`);
  }
});
