import { fillTemplate } from '../util/template.js';
import { GENERATED_NOTICE } from './notice.js';
import { CONVENTION_KEYS, conventionDisplay } from '../conventions.js';

const JENKINS_SNIPPET = `// Generated by stackcrew {{sc:version}}: paste this stage into your Jenkinsfile.
// Shallow/multibranch clones: fetch the target branch first (git fetch origin <target>), otherwise check fails loudly.
stage('stackcrew check') {
  steps {
    sh 'npx --yes stackcrew@{{sc:version}} check --base "origin/\${CHANGE_TARGET:-main}"'
  }
}
`;

const BS = String.fromCharCode(92);
const CR = String.fromCharCode(13);
const LF = String.fromCharCode(10);
const cell = (s) => String(s).replaceAll(CR + LF, ' ').replaceAll(LF, ' ').replaceAll(CR, ' ').replaceAll('|', BS + '|');

function renderProfileDoc(ctx) {
  const { profile, stack, addons } = ctx;
  const lines = [GENERATED_NOTICE, '', '# Architecture profile', '', '## Stack', '', `${stack.name} (minimum version ${stack.minVersion})`, '', '## Add-ons', ''];
  if (addons.length === 0) lines.push('_None._');
  else for (const a of addons) lines.push(`- ${a.name}`);

  lines.push('', '## Context', '');
  const entries = Object.entries(profile.context ?? {});
  if (entries.length === 0) lines.push('_No context recorded yet — run the stackcrew-init interview._');
  else {
    lines.push('| Key | Value |', '| --- | --- |');
    for (const [k, v] of entries) lines.push(`| ${cell(k)} | ${cell(v)} |`);
  }

  lines.push('', '## Conventions', '', '| Key | Value | Source |', '| --- | --- | --- |');
  const declared = profile.conventions ?? {};
  for (const k of CONVENTION_KEYS) {
    const source = Object.prototype.hasOwnProperty.call(declared, k) ? 'stackcrew.json' : 'default';
    lines.push(`| ${cell(k)} | ${cell(conventionDisplay(ctx.conventions, k))} | ${source} |`);
  }

  lines.push('', '## Decisions', '');
  const decisions = profile.decisions ?? [];
  if (decisions.length === 0) lines.push('_No decisions recorded yet._');
  decisions.forEach((d, i) => {
    if (i > 0) lines.push('');
    const rejected = d.rejected && d.rejected.length > 0 ? d.rejected.join('; ') : '—';
    lines.push(`### ${d.id} — ${d.area}`, '', `**Decision:** ${d.decision}`, '', `**Rationale:** ${d.rationale}`, '', `**Rejected:** ${rejected}`);
  });

  lines.push('', '## How to change', '', 'Edit `stackcrew.json`, then run `stackcrew sync`.', '');
  return lines.join('\n');
}

/** @param {import('../types.js').RenderContext} ctx @returns {import('../types.js').FileOp[]} */
export function renderShared(ctx) {
  const { profile, stack, language, vars } = ctx;
  /** @type {import('../types.js').FileOp[]} */
  const ops = [{ path: 'docs/stackcrew/architecture-profile.md', kind: 'owned', content: renderProfileDoc(ctx) }];

  const guard = { version: 1, enabled: profile.guard, rules: [...language.guard, ...stack.guard] };
  ops.push({ path: '.stackcrew/guard.json', kind: 'owned', content: JSON.stringify(guard, null, 2) + '\n' });

  for (const f of stack.lintFiles) {
    ops.push({ path: `.stackcrew/lint/${f.relPath}`, kind: 'owned', content: fillTemplate(f.content, vars) });
  }

  const basePackage = vars.basePackage;
  if (profile.java?.wired === true && basePackage) {
    const dir = `src/test/java/${basePackage.replaceAll('.', '/')}/stackcrew`;
    for (const f of stack.wireFiles) {
      ops.push({ path: `${dir}/${f.relPath}`, kind: 'owned', content: fillTemplate(f.content, vars) });
    }
  }

  ops.push({ path: '.stackcrew/ci/Jenkinsfile.stackcrew.groovy', kind: 'owned', content: fillTemplate(JENKINS_SNIPPET, vars) });
  return ops;
}
