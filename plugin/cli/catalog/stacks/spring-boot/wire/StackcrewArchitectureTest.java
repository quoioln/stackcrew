@AnalyzeClasses(packages = "{{sc:basePackage}}", importOptions = ImportOption.DoNotIncludeTests.class)
class StackcrewArchitectureTest {

    private static final String JSON_NODE = "com.fasterxml.jackson.databind.JsonNode";
    private static final String OBJECT_NODE = "com.fasterxml.jackson.databind.node.ObjectNode";
    private static final String MAP = "java.util.Map";
    private static final String OBJECT = "java.lang.Object";
    private static final String AUTOWIRED = "org.springframework.beans.factory.annotation.Autowired";

    // Brownfield safety: every rule is frozen. Existing violations are recorded in the archunit_store
    // directory (commit it; it may only shrink) and only NEW violations fail. The store may be created
    // without an extra archunit.properties resource: the key below is `freeze.store` + `default.allowStoreCreation`.
    static {
        ArchConfiguration.get().setProperty("freeze.store.default.allowStoreCreation", "true");
    }

    // Scope note: the untyped-payload rule scans ..service.. and ..domain.. only. Boundary deserialization of a
    // dynamic payload and framework configuration (Kafka client config, JWT claims) belong in infrastructure,
    // adapter or config packages, which are not scanned. A JSON attribute of a domain entity is a typed
    // record plus an AttributeConverter, not a Map<String, Object> or JsonNode field.

    /** SC-TYPE: no untyped payloads in service or domain fields, parameters or return types. */
    @ArchTest
    static final ArchRule no_untyped_payloads_in_service_and_domain = freeze(classes()
            .that().resideInAnyPackage("..service..", "..domain..")
            .should(notExposeUntypedPayloads())
            .allowEmptyShould(true));

    /** Constructor injection only. */
    @ArchTest
    static final ArchRule no_field_injection = freeze(noFields()
            .should().beAnnotatedWith(AUTOWIRED)
            .because("use constructor injection")
            .allowEmptyShould(true));

    /** Layering: a controller goes through a service, never straight to a repository. */
    @ArchTest
    static final ArchRule controllers_do_not_depend_on_repositories = freeze(noClasses()
            .that().resideInAnyPackage("..controller..", "..web..", "..api..")
            .should().dependOnClassesThat().resideInAnyPackage("..repository..", "..repositories..")
            .allowEmptyShould(true));

    /** Anti-corruption: provider DTOs live in infrastructure or adapter packages and must not leak into the domain. */
    @ArchTest
    static final ArchRule domain_does_not_depend_on_infrastructure = freeze(noClasses()
            .that().resideInAPackage("..domain..")
            .should().dependOnClassesThat().resideInAnyPackage("..infrastructure..", "..adapter..")
            .allowEmptyShould(true));

    private static ArchCondition<JavaClass> notExposeUntypedPayloads() {
        return new ArchCondition<>("not expose JsonNode, ObjectNode or Map with an Object value type") {
            @Override
            public void check(JavaClass javaClass, ConditionEvents events) {
                for (JavaField field : javaClass.getFields()) {
                    report(events, javaClass, field.getFullName() + " has field type " + field.getType().getName(), field.getType());
                }
                for (JavaCodeUnit unit : javaClass.getCodeUnits()) {
                    for (JavaType parameterType : unit.getParameterTypes()) {
                        report(events, javaClass, unit.getFullName() + " has parameter type " + parameterType.getName(), parameterType);
                    }
                    report(events, javaClass, unit.getFullName() + " has return type " + unit.getReturnType().getName(), unit.getReturnType());
                }
            }
        };
    }

    private static void report(ConditionEvents events, JavaClass owner, String message, JavaType type) {
        if (isUntyped(type)) {
            events.add(SimpleConditionEvent.violated(owner, message + " (SC-TYPE)"));
        }
    }

    /**
     * True for JsonNode, ObjectNode, or a Map whose value type is Object or an unbounded wildcard.
     * Type arguments are inspected recursively, so List&lt;JsonNode&gt; and Map&lt;String, List&lt;Map&lt;String, Object&gt;&gt;&gt; are caught too.
     */
    private static boolean isUntyped(JavaType type) {
        String rawName = type.toErasure().getName();
        if (JSON_NODE.equals(rawName) || OBJECT_NODE.equals(rawName)) {
            return true;
        }
        if (type instanceof JavaParameterizedType parameterized) {
            List<JavaType> arguments = parameterized.getActualTypeArguments();
            if (type.toErasure().isAssignableTo(MAP) && arguments.size() == 2 && isObjectOrWildcard(arguments.get(1))) {
                return true;
            }
            return arguments.stream().anyMatch(StackcrewArchitectureTest::isUntyped);
        }
        return false;
    }

    private static boolean isObjectOrWildcard(JavaType valueType) {
        if (valueType instanceof JavaWildcardType wildcard) {
            return wildcard.getLowerBounds().isEmpty()
                    && wildcard.getUpperBounds().stream().allMatch(bound -> OBJECT.equals(bound.toErasure().getName()));
        }
        return valueType instanceof JavaClass && OBJECT.equals(valueType.getName());
    }
}
